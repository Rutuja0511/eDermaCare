package com.example.edermacarelatestt;

public class Dermatologist {
    private String name;
    private String city;

    public Dermatologist(String name, String city) {
        this.name = name;
        this.city = city;
    }

    public String getName() {
        return name;
    }

    public String getCity() {
        return city;
    }
}

